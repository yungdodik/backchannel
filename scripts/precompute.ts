import { mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { liveDeps } from "@/lib/live";
import { createPipeline } from "@/lib/pipeline";
import { assertReport } from "@/lib/replay";
import type { StreamEvent } from "@/lib/types";

async function precompute(calaId: string): Promise<boolean> {
  const t0 = Date.now();
  const secs = () => ((Date.now() - t0) / 1000).toFixed(0);
  const pipeline = createPipeline(liveDeps({ budgetMs: Infinity }));
  let last: StreamEvent | undefined;
  for await (const e of pipeline.run(calaId)) {
    last = e;
    if (e.type === "progress") console.log(`[${secs()}s] ${e.message}`);
    else if (e.type === "entry") console.log(`[${secs()}s] entry: ${e.entry.companyName} / ${e.entry.founder.name}`);
  }
  if (last?.type !== "done") {
    console.error(last?.type === "error" ? `error: ${last.message}` : "stream ended without done");
    return false;
  }
  assertReport(last.report);
  mkdirSync("data/reports", { recursive: true });
  writeFileSync(`data/reports/${calaId}.json`, JSON.stringify(last.report, null, 2) + "\n");
  console.log(`wrote data/reports/${calaId}.json in ${secs()}s`);
  return true;
}

function writeIndex() {
  const ids = readdirSync("data/reports")
    .filter((f) => f.endsWith(".json"))
    .map((f) => f.slice(0, -5))
    .sort();
  const lines = ids.map((id) => `  "${id}": () => import("@/data/reports/${id}.json"),\n`);
  writeFileSync(
    "lib/cached-reports.ts",
    `// Generated by scripts/precompute.ts — do not edit by hand.
export const cachedReports: Record<string, () => Promise<{ default: unknown }>> = {${lines.length ? "\n" + lines.join("") : ""}};
`,
  );
}

async function main() {
  process.loadEnvFile(".env.local");
  let ok = true;
  for (const id of process.argv.slice(2)) ok = (await precompute(id)) && ok;
  writeIndex();
  if (!ok) process.exit(1);
}

void main();
